import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = fs.readFileSync(path.join(root, "assets/js/carioc-ia-site-index.js"), "utf8");
const match = source.match(/SITE_GUIDE_INDEX\s*=\s*(\[[\s\S]*?\]);/);
if (!match) throw new Error("SITE_GUIDE_INDEX not found");
const routes = JSON.parse(match[1]);
const decode = s => String(s || "").replace(/&amp;/g,"&").replace(/&quot;/g,'"').replace(/&#39;|&apos;/g,"'").replace(/&nbsp;/g," ").replace(/&lt;/g,"<").replace(/&gt;/g,">").replace(/&#(\d+);/g,(_,n)=>String.fromCodePoint(+n)).replace(/&#x([\da-f]+);/gi,(_,n)=>String.fromCodePoint(parseInt(n,16))).replace(/<[^>]+>/g," ").replace(/\s+/g," ").trim();
const strip = s => decode(s).replace(/\s*[|–—-]\s*.*$/, "").trim();
const normalize = s => String(s || "").normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
const hasLocation = (text, location) => {
  const escaped = location.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return new RegExp("(^|[^\\p{L}])" + escaped + "([^\\p{L}]|$)", "iu").test(text);
};
const locations = ["Copacabana","Ipanema","Leblon","Botafogo","Centro","Lapa","Santa Teresa","Barra da Tijuca","Urca","Flamengo","Recreio","Tijuca","Gávea","Lagoa","São Conrado","Arraial do Cabo","Búzios","Angra dos Reis"];
const items=[];
for (const [href,category,slug] of routes) {
  const htmlPath=path.join(root,href,"index.html");
  if (!fs.existsSync(htmlPath)) throw new Error(`Route has no source page: ${href}`);
  const html=fs.readFileSync(htmlPath,"utf8");
  const h1=strip(html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/i)?.[1] || "");
  const title=h1 || strip(html.match(/<title[^>]*>([\s\S]*?)<\/title>/i)?.[1] || slug);
  const description=decode(html.match(/<meta\s+[^>]*name=["']description["'][^>]*content=["']([^"']*)["']/i)?.[1] || html.match(/<meta\s+[^>]*content=["']([^"']*)["'][^>]*name=["']description["']/i)?.[1] || "");
  const main=html.match(/<main\b[^>]*>([\s\S]*?)<\/main>/i)?.[1] || html;
  const mainText=main.replace(/<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>/gi," ");
  const plain=decode(mainText).slice(0,18000);
  const lead=decode(main.match(/<p[^>]*class=["'][^"']*\blead\b[^"']*["'][^>]*>([\s\S]*?)<\/p>/i)?.[1] || "");
  const intro=decode(main.match(/<p\b[^>]*>([\s\S]*?)<\/p>/i)?.[1] || "");
  const genericDescription=/^(?:gu[ií]a editorial de .{1,100}: identidad, historia, recomendaciones, horarios, transporte y mapa en r[ií]o\.?|mi gu[ií]a de .{1,100}: qu[eé] esperar, c[oó]mo encajarlo en tu viaje)/i.test(description);
  const summary=lead || (description && !genericDescription ? description : intro || description || h1);
  const localityText=normalize([slug,h1,lead].join(" "));
  const neighborhood=locations.find(n=>hasLocation(localityText,normalize(n))) || "";
  const pageTags=[...main.matchAll(/<(?:span|a)\b[^>]*class=["'][^"']*\btag\b[^"']*["'][^>]*>([\s\S]*?)<\/(?:span|a)>/gi)]
    .map(match=>decode(match[1])).filter(tag=>tag && !/precio|price|faixa|cost/i.test(tag));
  const tags=[category,slug.replace(/-/g," "),...pageTags,...locations.filter(n=>hasLocation(localityText,normalize(n)))];
  for(const [pattern,tag] of [[/crianc|crian[cç]as|child|family|fam[ií]lia/i,"family"],[/acess[ií]vel|accessib|cadeirante/i,"accessible"],[/casal|rom[aâ]nt|couple/i,"couple"],[/veg|vegetarian|vegano/i,"vegetarian"],[/surf/i,"surf"],[/gr[aá]tis|free/i,"free"]]) if(pattern.test(plain)) tags.push(tag);
  const imageMatch=html.match(/<img\b[^>]*?src=["']([^"']+)["'][^>]*>/i) || html.match(/<img\b[^>]*?data-src=["']([^"']+)["'][^>]*>/i);
  let image=imageMatch?.[1] || "";
  if(image && !/^(?:https?:|data:|\/\/)/i.test(image)) image="/"+path.posix.normalize(path.posix.join(href,image)).replace(/^\/+/,"");
  const imageExists=image.startsWith("/") && fs.existsSync(path.join(root,image));
  items.push({href,category,slug,title,summary,neighborhood,tags:[...new Set(tags)],image:imageExists?image:""});
}
const json=JSON.stringify(items);
fs.writeFileSync(path.join(root,"assets/js/carioc-ia-site-index-data.js"),`// Generated by scripts/build_carioc_ia_site_index.mjs from existing source pages.\nexport const SITE_GUIDE_DOCUMENTS = ${json};\n`);
fs.writeFileSync(path.join(root,"docs/CARIOC_IA_SITE_INDEX_ROUTES.json"),JSON.stringify(items.map(({href,category})=>({href,category})),null,2)+"\n");
console.log(`Generated ${items.length} route records from repository pages.`);
